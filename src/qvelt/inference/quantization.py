"""Optional HQQ weight-only CPU path;serialize numeric tensors,never encoded dtype text."""

from __future__ import annotations

import copy
import json
import uuid
from datetime import UTC, datetime
from importlib.metadata import version
from pathlib import Path
from typing import Any

import torch
from safetensors.torch import load, save
from torch import Tensor, nn

from qvelt.config import config_digest, dump_config, parse_config
from qvelt.eval.config import ArtifactRef
from qvelt.inference.artifacts import InferenceSnapshot, checked_payload, load_snapshot
from qvelt.model.decoder import Decoder
from qvelt.tokenizer.core import QveltTokenizer
from qvelt.utils.artifacts import ArtifactStore, create_directory
from qvelt.utils.manifest_types import Manifest, RunInfo
from qvelt.utils.manifests import manifest_bytes, parse_manifest
from qvelt.utils.provenance import capture_code, capture_environment


def _hqq() -> tuple[Any, Any]:
    try:
        from hqq.core.quantize import BaseQuantizeConfig, HQQLinear
    except ImportError as error:
        raise RuntimeError("Install the frozen quantization extra for HQQ") from error
    return HQQLinear, BaseQuantizeConfig


def _quantize(model: Decoder, bits: int, group_size: int) -> Decoder:
    if (
        type(bits) is not int
        or bits not in (4, 8)
        or type(group_size) is not int
        or group_size != 32
    ):
        raise ValueError("Weight-only reference supports HQQ int4/int8,group32")
    if (
        model.training
        or model.config.parameter_count > 20_000_000
        or any(
            p.device.type != "cpu" or p.dtype != torch.float32
            for p in model.parameters()
        )
    ):
        raise ValueError("Quantization needs bounded CPU FP32 eval weights")
    linear, config = _hqq()
    model.requires_grad_(False)
    for module in list(model.modules()):
        for name, child in list(module.named_children()):
            if isinstance(child, nn.Linear):
                if child.in_features % group_size:
                    raise ValueError(
                        "Projection input width must divide HQQ group size"
                    )
                quantized = linear(
                    child,
                    config(nbits=bits, group_size=group_size, axis=1),
                    compute_dtype=torch.float32,
                    device="cpu",
                )
                quantized.W_q = nn.Parameter(
                    quantized.W_q.detach().clone(), requires_grad=False
                )
                quantized.meta = {
                    key: value.clone() if isinstance(value, Tensor) else value
                    for key, value in quantized.meta.items()
                }
                quantized.forward = quantized.forward_pytorch
                setattr(module, name, quantized)
    return model


def quantize_model(model: Decoder, bits: int, group_size: int = 32) -> Decoder:
    """Copy weights;real HQQ packing and pure PyTorch dequantize/matmul fallback."""
    with torch.inference_mode(False), torch.random.fork_rng(devices=[]):
        return _quantize(copy.deepcopy(model), bits, group_size)


def compact_state(model: Decoder) -> dict[str, Tensor]:
    """Only packed weights,FP32 gains/embedding,and numeric HQQ scales/zeros."""
    linear, _ = _hqq()
    tensors = {
        name: p.detach().contiguous().clone() for name, p in model.named_parameters()
    }
    for name, module in model.named_modules():
        if isinstance(module, linear):
            for key in ("scale", "zero"):
                tensors[name + ".meta." + key] = (
                    module.meta[key].detach().contiguous().clone()
                )
    return tensors


def restore_compact(model: Decoder, tensors: dict[str, Tensor]) -> None:
    """Metadata is regenerated by the pinned library;never call its dtype eval decoder."""
    expected = compact_state(model)
    if set(tensors) != set(expected) or any(
        value.shape != expected[name].shape
        or value.dtype != expected[name].dtype
        or value.device.type != "cpu"
        or not bool(torch.isfinite(value).all())
        for name, value in tensors.items()
    ):
        raise ValueError("Quantized tensor keys/shapes/dtypes/finiteness differ")
    linear, _ = _hqq()
    with torch.no_grad():
        for name, parameter in model.named_parameters():
            parameter.copy_(tensors[name])
        for name, module in model.named_modules():
            if isinstance(module, linear):
                for key in ("scale", "zero"):
                    module.meta[key] = tensors[name + ".meta." + key].clone()


def export_quantized(
    reference: ArtifactRef, directory: Path, repository: Path, *, bits: int
) -> Manifest:
    snapshot = load_snapshot(reference)
    model = quantize_model(snapshot.model, bits)
    root, code = capture_code(repository)
    owner = uuid.uuid4().hex
    store = ArtifactStore(create_directory(directory))
    descriptor = {
        "format": "qvelt-hqq-weights-v1",
        "bits": bits,
        "group_size": 32,
        "library": "hqq",
        "version": version("hqq"),
        "source_sha256": reference.sha256,
        "backend": "pytorch-fp32-cpu",
        "release_status": "engineering_quantization_not_model_release",
    }
    files = [
        store.add_bytes(
            "model.safetensors", save(compact_state(model)), role="quantized_weights"
        ),
        store.add_bytes(
            "config.yaml", dump_config(snapshot.config).encode(), role="config"
        ),
        store.add_bytes(
            "tokenizer.json", snapshot.tokenizer.to_bytes(), role="tokenizer"
        ),
        store.add_bytes(
            "quantization.json",
            (json.dumps(descriptor, sort_keys=True) + "\n").encode(),
            role="quantization_descriptor",
        ),
        store.add_bytes(
            "source.manifest.json",
            manifest_bytes(snapshot.manifest),
            role="source_snapshot_manifest",
        ),
        store.add_file("uv.lock", root / "uv.lock", role="dependency_lock"),
        store.add_file("LICENSE", repository / "LICENSE", role="code_license"),
        store.add_file("NOTICE", repository / "NOTICE", role="code_notice"),
    ]
    manifest = Manifest(
        "run",
        owner,
        datetime.now(UTC).isoformat(),
        RunInfo(
            owner,
            config_digest(snapshot.config),
            code,
            capture_environment(),
            snapshot.config.runtime.seed,
            1,
        ),
        tuple(files),
    )
    store.publish(manifest)
    return manifest


def load_quantized(reference: ArtifactRef) -> InferenceSnapshot:
    path = Path(reference.path)
    store = ArtifactStore(path.parent)
    manifest = store.read_manifest(
        path.name, expected_sha256=reference.sha256, verify=False
    )
    roles = {
        "quantized_weights",
        "dependency_lock",
        "config",
        "tokenizer",
        "quantization_descriptor",
        "source_snapshot_manifest",
        "code_license",
        "code_notice",
    }
    if (
        not isinstance(manifest.metadata, RunInfo)
        or len(manifest.files) != len(roles)
        or {f.role for f in manifest.files} != roles
        or sum(f.size_bytes for f in manifest.files) > 256 * 1024**2
    ):
        raise ValueError("Invalid bounded quantized artifact")
    store.verify(manifest)
    from qvelt.eval.corpus import read_json

    descriptor = read_json(
        checked_payload(store, manifest, "quantization_descriptor", 4096)
    )
    if (
        not isinstance(descriptor, dict)
        or set(descriptor)
        != {
            "format",
            "bits",
            "group_size",
            "library",
            "version",
            "source_sha256",
            "backend",
            "release_status",
        }
        or descriptor["format"] != "qvelt-hqq-weights-v1"
        or descriptor["library"] != "hqq"
        or descriptor["version"] != version("hqq")
        or descriptor["backend"] != "pytorch-fp32-cpu"
        or descriptor["release_status"] != "engineering_quantization_not_model_release"
    ):
        raise ValueError("Unsupported quantization descriptor/library")
    config_bytes = checked_payload(store, manifest, "config", 128 * 1024)
    config = parse_config(config_bytes.decode())
    if (
        config_digest(config) != manifest.metadata.config_sha256
        or config.model.parameter_count > 20_000_000
        or config.runtime.device != "cpu"
        or config.runtime.precision != "fp32"
    ):
        raise ValueError("Quantized config identity/capacity mismatch")
    source = parse_manifest(
        checked_payload(store, manifest, "source_snapshot_manifest", 1024**2),
        expected_sha256=descriptor["source_sha256"],
    )
    tokenizer_bytes = checked_payload(store, manifest, "tokenizer", 64 * 1024**2)
    if (
        not isinstance(source.metadata, RunInfo)
        or source.metadata.config_sha256 != manifest.metadata.config_sha256
    ):
        raise ValueError("Quantization source/config mismatch")
    for role in ("config", "tokenizer"):
        actual = next(f for f in manifest.files if f.role == role)
        original = [f for f in source.files if f.role == role]
        if (
            len(original) != 1
            or actual.sha256 != original[0].sha256
            or actual.size_bytes != original[0].size_bytes
        ):
            raise ValueError("Quantized config/tokenizer differs from native source")
    tokenizer = QveltTokenizer.from_bytes(tokenizer_bytes)
    if tokenizer.vocab_size != config.model.vocab:
        raise ValueError("Quantized tokenizer vocabulary mismatch")
    tensors = load(checked_payload(store, manifest, "quantized_weights", 128 * 1024**2))
    with (
        torch.inference_mode(False),
        torch.random.fork_rng(devices=[]),
        torch.device("cpu"),
    ):
        torch.manual_seed(0)
        model = _quantize(
            Decoder(config.model).eval(), descriptor["bits"], descriptor["group_size"]
        )
        restore_compact(model, tensors)
    return InferenceSnapshot(model, tokenizer, config, manifest)
